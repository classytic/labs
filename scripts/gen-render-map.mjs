/**
 * Regenerate src/domains/render-map.ts — a PURE per-lab runtime-loader map for the learner
 * render path. No zod, no schemas, no manifest objects: just `id → () => import('<runtime>')`
 * (each a literal dynamic import → its own chunk) + an `id → tag` map. So a lesson player pulls
 * only tiny loaders and downloads only the labs it actually renders — not every lab's metadata.
 *
 * Reads the manifest SOURCE files directly (id/domain/tag are literals), so it needs no build and
 * no machine-specific paths. Run when manifests change:  node scripts/gen-render-map.mjs
 */
import { writeFileSync, existsSync, readdirSync, readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const CHECK = process.argv.includes('--check');
// Only generate when run directly (`node scripts/gen-render-map.mjs`); when imported for
// `readManifests` (e.g. by gen-manifests / labs-check) this must have no side effects.
const IS_MAIN = import.meta.url === pathToFileURL(process.argv[1] ?? '').href;

const DOMAINS_DIR = new URL('../src/domains/', import.meta.url);
const pascal = (id) =>
  id.replace(/-([a-z])/g, (_, c) => c.toUpperCase()).replace(/^./, (c) => c.toUpperCase());
const field = (text, name) => {
  const match = text.match(new RegExp(`\\b${name}:\\s*(["'])(.*?)\\1`));
  return match?.[2];
};

/** Scan src/domains/<domain>/<id>/manifest.ts → { id, domain, tag, rt }. */
export function readManifests() {
  const rows = [];
  for (const domain of readdirSync(DOMAINS_DIR, { withFileTypes: true })) {
    if (!domain.isDirectory()) continue;
    const domainDir = new URL(`${domain.name}/`, DOMAINS_DIR);
    for (const lab of readdirSync(domainDir, { withFileTypes: true })) {
      if (!lab.isDirectory()) continue;
      const manifestPath = new URL(`${lab.name}/manifest.ts`, domainDir);
      if (!existsSync(manifestPath)) continue;
      const text = readFileSync(manifestPath, 'utf8');
      const id = field(text, 'id');
      const dom = field(text, 'domain') ?? domain.name;
      if (!id) throw new Error(`no id literal in ${domain.name}/${lab.name}/manifest.ts`);
      if (lab.name !== id)
        throw new Error(`folder ${domain.name}/${lab.name} !== id '${id}' (folder must equal id)`);
      const base = new URL(`${lab.name}/`, domainDir);
      const rt =
        existsSync(new URL('runtime.tsx', base)) || existsSync(new URL('runtime.ts', base))
          ? `./${dom}/${id}/runtime.js`
          : `./${dom}/${id}/runtime/index.js`;
      rows.push({ id, domain: dom, tag: field(text, 'tag') ?? pascal(id), rt });
    }
  }
  return rows.sort((a, b) => (a.domain + a.id).localeCompare(b.domain + b.id));
}

function generate() {
  const rows = readManifests();
  const loaders = rows.map((r) => `  '${r.id}': () => import('${r.rt}'),`).join('\n');
  const tags = rows.map((r) => `  '${r.id}': '${r.tag}',`).join('\n');

  const out = `/**
 * GENERATED by scripts/gen-render-map.mjs — do not edit by hand.
 *
 * PURE per-lab runtime loaders + an id→tag map. No schema/zod/manifest imports, so the learner
 * render map (domains/render.tsx) stays light: only the labs a lesson uses download their chunk,
 * and no lab's metadata is pulled just to render another.
 */
/* eslint-disable @typescript-eslint/no-explicit-any */
import type { ReactNode } from 'react';

export type LabRuntimeLoader = () => Promise<{ default: (attrs: any) => ReactNode }>;

/** ${rows.length} labs, keyed by lab id. */
export const labRuntimeLoaders: Record<string, LabRuntimeLoader> = {
${loaders}
};

/** lab id → MDX tag. */
export const labTags: Record<string, string> = {
${tags}
};
`;
  const target = new URL('../src/domains/render-map.ts', import.meta.url);
  if (CHECK) {
    const cur = existsSync(target) ? readFileSync(target, 'utf8') : '';
    if (cur !== out) {
      console.error('✗ render-map.ts is stale — run: node scripts/gen-render-map.mjs');
      process.exit(1);
    }
    console.log('✓ render-map.ts up to date:', rows.length, 'labs');
  } else {
    writeFileSync(target, out);
    console.log('wrote src/domains/render-map.ts:', rows.length, 'labs');
  }
}

if (IS_MAIN) generate();
