/** Generate lazy loaders for canonical pure activity.ts plans. Quality tooling opts in;
 * learner catalogs and render maps never import this module. */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';

const CHECK = process.argv.includes('--check');
const root = new URL('../src/domains/', import.meta.url);
const rows = [];
for (const domain of readdirSync(root, { withFileTypes: true })) {
  if (!domain.isDirectory()) continue;
  const domainRoot = new URL(`${domain.name}/`, root);
  for (const lab of readdirSync(domainRoot, { withFileTypes: true })) {
    if (!lab.isDirectory()) continue;
    const activity = new URL(`${lab.name}/activity.ts`, domainRoot);
    if (existsSync(activity)) rows.push({ id: lab.name, path: `./${domain.name}/${lab.name}/activity.js` });
  }
}
rows.sort((a, b) => a.id.localeCompare(b.id));
const loaders = rows.map(({ id, path }) => `  '${id}': () => import('${path}'),`).join('\n');
const output = `/** GENERATED by scripts/gen-activity-map.mjs — do not edit.
 * Opt-in quality loaders only; never import from learner catalogs. */
import type { CompiledAuthoredActivity } from '../kit/activity-authoring.js';

export type ActivityPlanLoader = () => Promise<{ activity: CompiledAuthoredActivity }>;

export const activityPlanLoaders: Record<string, ActivityPlanLoader> = {
${loaders}
};
`;
const target = new URL('../src/domains/activity-map.ts', import.meta.url);
if (CHECK) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== output) {
    console.error('✗ activity-map.ts is stale — run: node scripts/gen-activity-map.mjs');
    process.exit(1);
  }
  console.log(`✓ activity-map.ts up to date: ${rows.length} authored plans`);
} else {
  writeFileSync(target, output);
  console.log(`wrote src/domains/activity-map.ts: ${rows.length} authored plans`);
}
