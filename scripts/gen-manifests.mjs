/**
 * Regenerate src/domains/manifests.ts — the production manifest REGISTRY. Scans every
 * src/domains/<domain>/<id>/manifest.ts and composes them into `labManifests`, so adding a lab is
 * just adding its folder (then `npm run labs:generate`) — no hand-editing this barrel. LIGHT: a
 * manifest imports only its pure schema + the defineLab factory, never its runtime.
 *
 *   node scripts/gen-manifests.mjs           # write
 *   node scripts/gen-manifests.mjs --check    # fail if the on-disk file is stale (CI drift guard)
 */
import { writeFileSync, existsSync, readFileSync } from 'node:fs';
import { readManifests } from './gen-render-map.mjs';

const CHECK = process.argv.includes('--check');
const camel = (id) => id.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

const rows = readManifests(); // sorted by domain+id, validates folder==id + duplicate-safe upstream
const byDomain = new Map();
for (const r of rows) {
  if (!byDomain.has(r.domain)) byDomain.set(r.domain, []);
  byDomain.get(r.domain).push(r);
}
const domains = [...byDomain.keys()].sort();

const importLines = [];
const arrayLines = [];
for (const d of domains) {
  const labs = byDomain.get(d);
  importLines.push(`// ${d}`);
  for (const r of labs) importLines.push(`import ${camel(r.id)} from './${d}/${r.id}/manifest.js';`);
  importLines.push('');
  arrayLines.push(`  // ${d}`);
  const names = labs.map((r) => camel(r.id));
  for (let i = 0; i < names.length; i += 8) arrayLines.push('  ' + names.slice(i, i + 8).join(', ') + ',');
}

const out = `/**
 * GENERATED by scripts/gen-manifests.mjs — do not edit by hand. Add a lab folder + run
 * \`npm run labs:generate\`. Each entry is ONE lab in the canonical model
 * (src/domains/<domain>/<lab-id>/manifest.ts); a manifest pulls only its pure schema + the
 * defineLab factory, never its runtime, so listing every manifest here stays cheap.
 */
import type { LabManifest } from '../lab-def/define-lab.js';

${importLines.join('\n')}
export const labManifests: readonly LabManifest[] = [
${arrayLines.join('\n')}
];
`;

const target = new URL('../src/domains/manifests.ts', import.meta.url);
if (CHECK) {
  const cur = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (cur !== out) {
    console.error('✗ manifests.ts is stale — run: node scripts/gen-manifests.mjs');
    process.exit(1);
  }
  console.log('✓ manifests.ts up to date:', rows.length, 'labs');
} else {
  writeFileSync(target, out);
  console.log('wrote src/domains/manifests.ts:', rows.length, 'labs');
}
